'use strict';
const fs = require('fs');
const path = require('path');
const { compareVersions } = require('./util');

// Password check for Java Edition servers. Vanilla Java has no scripting, so it is split in two:
//
//   - A data pack in the world (written on every start) keeps everyone who has not entered the password locked:
//     dark screen, no walking or jumping, no reach to blocks or entities. It works without the portal, so if the
//     portal goes away nobody new gets in ("fail closed").
//   - Players type the password with  /trigger pin set <password>. The server logs every /trigger use on its
//     console (gamerule log_admin_commands), the portal reads it, compares the password and, when it matches,
//     marks the player with a tag that the data pack unlocks. Wrong guesses and time-outs are kicked by the portal.
//
// The tag only counts together with this run's id (set when the data pack loads), so a tag left over from an
// earlier start of the server is worthless; leaving the server also clears it.
const PACK = 'mcf_auth';
const TRIGGER = 'pin';
const TAG_OK = 'mcf_ok';
const TAG_LOCKED = 'mcf_locked';
const OBJ = 'mcf';

const atLeast = (version, min) => compareVersions(version, min) >= 0;

// Attribute ids lost their "generic." / "player." prefix in 1.21.2.
function attributes(version) {
  const plain = atLeast(version, '1.21.2');
  return [
    plain ? 'minecraft:movement_speed' : 'minecraft:generic.movement_speed',
    plain ? 'minecraft:jump_strength' : 'minecraft:generic.jump_strength',
    plain ? 'minecraft:block_interaction_range' : 'minecraft:player.block_interaction_range',
    plain ? 'minecraft:entity_interaction_range' : 'minecraft:player.entity_interaction_range',
  ];
}

// Text components: clickEvent/hoverEvent became click_event/hover_event (with renamed fields) in 1.21.5.
function suggestText(version, text, command, hover) {
  const json = { text, color: 'aqua', underlined: true };
  if (atLeast(version, '1.21.5')) {
    json.click_event = { action: 'suggest_command', command };
    json.hover_event = { action: 'show_text', value: hover };
  } else {
    json.clickEvent = { action: 'suggest_command', value: command };
    json.hoverEvent = { action: 'show_text', contents: hover };
  }
  return json;
}

function packMeta(dataPack) {
  const description = 'Server Farm password check';
  // 1.21.9 (format 88) introduced min_format/max_format; older versions read the single pack_format number.
  if (dataPack.major >= 82) {
    const f = [dataPack.major, dataPack.minor || 0];
    return { pack: { description, min_format: f, max_format: f } };
  }
  return { pack: { description, pack_format: dataPack.major } };
}

const tellraw = (target, json) => `tellraw ${target} ${JSON.stringify(json)}`;

function files({ version, dataPack, protect, runId }) {
  const attrs = attributes(version);
  const NEW = `@a[tag=!${TAG_OK},tag=!${TAG_LOCKED}]`;
  const LOCKED = `@a[tag=${TAG_LOCKED}]`;
  const DONE = `@a[tag=${TAG_OK},tag=${TAG_LOCKED}]`;
  const command = `/trigger ${TRIGGER} set `;

  const unlock = [
    '# Unlock players who entered the password (or every locked player when protection is off).',
    ...attrs.map((a) => `execute as ${protect ? DONE : LOCKED} run attribute @s ${a} modifier remove mcf:lock`),
    `effect clear ${protect ? DONE : LOCKED} minecraft:blindness`,
    `effect clear ${protect ? DONE : LOCKED} minecraft:resistance`,
    `title ${protect ? DONE : LOCKED} clear`,
    `scoreboard players reset ${protect ? DONE : LOCKED} ${TRIGGER}`,
    `tag ${protect ? DONE : LOCKED} remove ${TAG_LOCKED}`,
  ];

  const load = [
    '# Generated by minecraft-server-farm on every start. Do not edit.',
    `scoreboard objectives add ${TRIGGER} trigger "비밀번호"`,
    `scoreboard objectives add ${OBJ} dummy`,
    `scoreboard objectives add ${OBJ}_left minecraft.custom:minecraft.leave_game`,
    `scoreboard players set #run ${OBJ} ${runId}`,
    `scoreboard players set #alive ${OBJ} 0`,
    `scoreboard players set #tick ${OBJ} 0`,
  ];

  const tick = protect
    ? [
      '# Generated by minecraft-server-farm on every start. Do not edit.',
      `scoreboard players set #alive ${OBJ} 1`,
      '# Leaving ends the session: whoever comes back enters the password again.',
      `tag @a[scores={${OBJ}_left=1..}] remove ${TAG_OK}`,
      `scoreboard players reset @a[scores={${OBJ}_left=1..}] ${OBJ}_left`,
      '# A password entered during an earlier start of the server does not count.',
      `execute as @a[tag=${TAG_OK}] unless score @s ${OBJ} = #run ${OBJ} run tag @s remove ${TAG_OK}`,
      '# Lock newcomers: no walking or jumping, no reach to blocks or entities.',
      ...attrs.map((a) => `execute as ${NEW} run attribute @s ${a} modifier add mcf:lock -1 add_multiplied_total`),
      `title ${NEW} times 10 200 20`,
      `title ${NEW} subtitle {"text":"채팅창(T)에 /trigger ${TRIGGER} set <비밀번호>","color":"yellow"}`,
      `title ${NEW} title {"text":"비밀번호를 입력하세요","color":"gold"}`,
      `execute as ${NEW} run function mcf:prompt`,
      `tag ${NEW} add ${TAG_LOCKED}`,
      `effect give ${LOCKED} minecraft:blindness infinite 0 true`,
      `effect give ${LOCKED} minecraft:resistance infinite 4 true`,
      `scoreboard players enable ${LOCKED} ${TRIGGER}`,
      `scoreboard players add #tick ${OBJ} 1`,
      `execute if score #tick ${OBJ} matches 40.. run scoreboard players set #tick ${OBJ} 0`,
      `execute if score #tick ${OBJ} matches 0 run title ${LOCKED} actionbar {"text":"비밀번호를 입력해야 플레이할 수 있습니다","color":"yellow"}`,
      ...unlock,
    ]
    : [
      '# Generated by minecraft-server-farm on every start. Do not edit.',
      '# Password protection is off: just undo anything left over from a protected session.',
      `scoreboard players set #alive ${OBJ} 1`,
      ...unlock,
    ];

  // Run as a player (by the data pack when they are locked, and by the portal after a wrong guess).
  const prompt = [
    tellraw('@s', ['', { text: '[서버] ', color: 'gold' }, { text: '이 서버는 비밀번호로 보호되어 있습니다. ', color: 'white' },
      suggestText(version, '여기를 눌러', command, '채팅창에 명령어를 채워 줍니다'),
      { text: ` 비밀번호를 입력하세요. (${command}<비밀번호>)`, color: 'white' }]),
  ];

  return {
    'pack.mcmeta': JSON.stringify(packMeta(dataPack), null, 2),
    'data/minecraft/tags/function/load.json': JSON.stringify({ values: ['mcf:load'] }),
    'data/minecraft/tags/function/tick.json': JSON.stringify({ values: ['mcf:tick'] }),
    'data/mcf/function/load.mcfunction': `${load.join('\n')}\n`,
    'data/mcf/function/tick.mcfunction': `${tick.join('\n')}\n`,
    'data/mcf/function/prompt.mcfunction': `${prompt.join('\n')}\n`,
  };
}

// Writes the data pack into <worldDir>/datapacks/mcf_auth (replacing what was there).
function writePack(worldDir, opts) {
  const dir = path.join(worldDir, 'datapacks', PACK);
  fs.rmSync(dir, { recursive: true, force: true });
  for (const [rel, text] of Object.entries(files(opts))) {
    const file = path.join(dir, ...rel.split('/'));
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, text);
  }
}

// How to address a player in a command: a plain name when it is a normal Minecraft name, otherwise a selector
// (offline-mode servers accept odd names).
function target(name) {
  const s = String(name);
  if (/^[A-Za-z0-9_]{1,16}$/.test(s)) return s;
  return `@a[name="${s.replace(/[\\"]/g, '\\$&')}",limit=1]`;
}

// Console commands the portal sends once a player typed the right password.
function grantCommands(name, runId) {
  const t = target(name);
  return [
    `scoreboard players set ${t} ${OBJ} ${runId}`,
    `tag ${t} add ${TAG_OK}`,
    tellraw(t, { text: '[서버] 인증되었습니다. 즐거운 시간 되세요!', color: 'green' }),
  ];
}

function retryCommands(name, left) {
  const t = target(name);
  return [
    tellraw(t, { text: `[서버] 비밀번호가 틀렸습니다. (남은 기회 ${left}회)`, color: 'red' }),
    `execute as ${t} run function mcf:prompt`,
  ];
}

module.exports = { writePack, files, target, grantCommands, retryCommands, PACK, TRIGGER, TAG_OK, OBJ };
